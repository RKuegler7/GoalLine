<x-legal-page title="Privacy policy" updated="October 22, 2026">
    <p>GoalLine helps you plan and reach your goals, alone or with friends. This page explains, in plain language, what we collect, why, and the choices you have. GoalLine is in a private beta, and we&rsquo;ll update this page as it grows.</p>

    <h2>What we collect</h2>
    <ul>
        <li><strong>Your account:</strong> name, email, username, password (stored encrypted, never readable), time zone, and anything you add to your locker, like a photo, bio, or location.</li>
        <li><strong>Your goals and progress:</strong> goals, roadmaps, tasks, habits, check-ins, milestones, weekly reviews, and plan materials you upload.</li>
        <li><strong>What you share:</strong> posts, highlights, photos (with location data removed), kudos, comments, GoalLeague chat messages, your friends, and any reports you make. Posts go only to the audience you pick: your GoalLeague, or your GoalLeague and friends.</li>
        <li><strong>Notifications:</strong> your notification settings, and if you turn on push notifications, a technical address for your device from your browser&rsquo;s push service.</li>
        <li><strong>How you use GoalLine:</strong> which features are used and when (for example &ldquo;checked off a task&rdquo; or &ldquo;opened the app today&rdquo;), so we can see what&rsquo;s working. We don&rsquo;t record the content of what you write for this.</li>
    </ul>

    <h2>How we use it</h2>
    <ul>
        <li>To run GoalLine for you: your roadmap, Today&rsquo;s Gameplan, scoring, GoalLeagues, reminders, and notifications.</li>
        <li>To show what you share to the people your settings allow: your locker&rsquo;s visibility setting controls who sees your profile and highlights.</li>
        <li>To improve GoalLine, using feature-use counts.</li>
        <li>To keep GoalLine safe and working, including fixing errors.</li>
    </ul>
    <p>We don&rsquo;t sell your information, and we don&rsquo;t use it for advertising.</p>

    <h2>AI coaching</h2>
    <p>Roadmaps, coach checks, plan reading, and weekly tips are written by Claude, an AI model from Anthropic. To do that, GoalLine sends the relevant details to Anthropic: your goal, your plan, uploaded plan materials, and your weekly reflections. Anthropic processes this to answer the request under its commercial terms, which don&rsquo;t allow using it to train their models. AI suggestions can be wrong; they aren&rsquo;t professional, medical, financial, or legal advice.</p>

    <h2>Who else handles your data</h2>
    <ul>
        <li><strong>Hosting:</strong> GoalLine runs on Amazon Web Services, which stores the app&rsquo;s data and files.</li>
        <li><strong>Email:</strong> an email provider delivers account emails, reminders, and notifications.</li>
        <li><strong>Push notifications:</strong> your browser&rsquo;s push service (for example Apple, Google, or Mozilla) delivers them to your device.</li>
        <li><strong>AI:</strong> Anthropic, as described above.</li>
    </ul>

    <h2>Your choices</h2>
    <ul>
        <li>Choose who sees your locker: only you, your GoalLeagues, or everyone.</li>
        <li>Turn reminders, emails, and push notifications on or off for each kind of notification in Settings.</li>
        <li>Edit or remove your goals, highlights, comments, and photos at any time.</li>
        <li>Delete your account from your profile settings. That removes your account, goals, highlights, and uploaded files.</li>
    </ul>

